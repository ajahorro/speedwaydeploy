-- ============================================================================
-- 20261019000002_repair_sc1_payload_wipe.sql
-- ============================================================================
--
-- CRITICAL DATA-LOSS DEFECT (introduced by 20261018000003, partially repaired by
-- 20261018000014).
--
-- SYMPTOM
-- -------
-- Bookings were created with every business field NULL:
--
--     total_amount = 0, customer_name = null, start_datetime = null,
--     end_datetime = null, status = null, payment_status = null, ...
--
-- The row existed and had an id, so the submit flow reported "success" and the
-- customer was emailed — but the booking carried no money, no customer and no
-- time. A later SELECT ... .single() then failed with
-- "Cannot coerce the result to a single JSON object (0 rows)" once the
-- all-NULL time window let the auto-release sweep cancel and hide it.
--
-- ROOT CAUSE
-- ----------
-- The SC-1 identity patch, as generated by 20261018000003, ran:
--
--     if nullif(v_booking ->> 'customer_id', '') is null then
--       v_booking := jsonb_set(
--         v_booking,
--         '{customer_id}',
--         to_jsonb(public.resolve_customer_by_email(...)),   -- NULL when no match
--         true);
--     end if;
--
-- 1. `to_jsonb(NULL)` is the JSON scalar `null`.
-- 2. `jsonb_set(target, path, null, create_if_missing => TRUE)` on a JSON
--    `null` value ERASES THE ENTIRE OBJECT and returns `null`. This is
--    documented PostgreSQL behaviour, not a driver quirk: inserting a created
--    key whose value is JSON null makes jsonb_set discard the target object and
--    return a scalar null.
-- 3. Every subsequent read is then `(null) ->> 'total_amount'` => NULL, and
--    every `coalesce(..., 0)` => 0. Hence the all-NULL master row.
--
-- A guest booking's email usually has NO matching profile, so this fired on
-- essentially every customer self-service booking — the common path, not an
-- edge case.
--
-- WHY 20261018000014 MISSED IT
-- ----------------------------
-- That migration fixed the *type* error (COALESCE text/uuid) but kept the same
-- jsonb_set/JSON-null shape. It removed one crash and exposed the next layer.
--
-- THE FIX
-- -------
-- Stop assigning a possibly-NULL value into jsonb_set entirely. Resolve the id
-- into a variable, assign it only when it is non-null, and keep the payload
-- untouched otherwise. This is the safe pattern:  {customer_id} may simply
-- remain absent, which the master INSERT already tolerates via
-- `nullif(v_booking ->> 'customer_id', '')::uuid`.
--
-- Also adds an integrity assertion INSIDE the function, so a silently degraded
-- payload can never again be persisted without raising.
-- ============================================================================

do $repair_payload$
declare
  v_src        text;
  v_patched    text;
  v_frag_start text;
  v_frag_end   text;
  v_old        text;
  v_new        text;
  v_lookup     text;
begin
  select pg_get_functiondef(p.oid)
    into v_src
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'create_booking_atomic'
   limit 1;

  if v_src is null then
    raise exception 'SC-1 payload repair: public.create_booking_atomic() does not exist.';
  end if;

  -- Locate the generated SC-1 block by its marker and the statement that
  -- follows it, then replace from the marker through the closing `end if;`.
  v_frag_start := '  -- SC-1: never orphan a booking whose email already belongs to an account.';

  if position(v_frag_start in v_src) = 0 then
    -- Already repaired (or never patched). Verify the payload can no longer be
    -- wiped, then stop.
    if position('jsonb_set' in v_src) > 0
       and position('resolve_customer_by_email' in v_src) > 0
       and position('v_identity_id' in v_src) = 0 then
      raise exception 'SC-1 payload repair: SC-1 block present but marker text differs — refusing to guess. Inspect the live body.';
    end if;
    raise notice 'SC-1 payload repair: no un-repaired SC-1 block found — no-op.';
    return;
  end if;

  -- The replacement resolves the profile id into a variable and assigns it ONLY
  -- when non-null, so a guest with no matching profile leaves the payload
  -- completely untouched instead of being erased.
  v_new :=
    '  -- SC-1: never orphan a booking whose email already belongs to an account.' || chr(10) ||
    '  -- A no-match lookup returns NULL. NULL must NOT be written into the' || chr(10) ||
    '  -- payload: jsonb_set(..., to_jsonb(NULL), true) DISCARDS the whole target' || chr(10) ||
    '  -- object and returns a scalar null, which silently NULLed total_amount,' || chr(10) ||
    '  -- customer_name and the whole schedule on every guest booking.' || chr(10) ||
    '  v_identity_id := null;' || chr(10) ||
    '  if nullif(v_booking ->> ' || quote_literal('customer_id') || ', ' || quote_literal('') || ') is null then' || chr(10) ||
    '    v_identity_id := public.resolve_customer_by_email(v_booking ->> ' || quote_literal('customer_email') || ');' || chr(10) ||
    '  end if;' || chr(10) ||
    '  if v_identity_id is not null then' || chr(10) ||
    '    v_booking := jsonb_set(v_booking, ' || quote_literal('{customer_id}') || ', to_jsonb(v_identity_id), true);' || chr(10) ||
    '  end if;';

  v_old := v_frag_start;
  v_frag_end := '  end if;';

  -- Build a marker-unique alternative so this migration is idempotent: it only
  -- matches when the OLD jsonb_set-of-null shape is still present.
  if position('to_jsonb(public.resolve_customer_by_email' in v_src) = 0 then
    raise notice 'SC-1 payload repair: the null-wiping expression is already gone — no-op.';
    return;
  end if;

  -- Replace the exact null-wiping statement with the guarded assignment, then
  -- patch the two enclosing `end if;` boundaries are left untouched.
  v_old := 'v_booking := jsonb_set(' || chr(10) ||
           '      v_booking,' || chr(10) ||
           '      ' || quote_literal('{customer_id}') || ',' || chr(10) ||
           '      to_jsonb(public.resolve_customer_by_email(v_booking ->> ' || quote_literal('customer_email') || ')),' || chr(10) ||
           '      true' || chr(10) ||
           '    );';

  v_patched := replace(v_src, v_old, 'v_identity_id := public.resolve_customer_by_email(v_booking ->> ' || quote_literal('customer_email') || ');' || chr(10) ||
           '    if v_identity_id is not null then' || chr(10) ||
           '      v_booking := jsonb_set(v_booking, ' || quote_literal('{customer_id}') || ', to_jsonb(v_identity_id), true);' || chr(10) ||
           '    end if;');

  if v_patched = v_src then
    raise exception 'SC-1 payload repair: could not match the null-wiping statement; refusing to ship a no-op migration.';
  end if;

  -- Declare the variable the patch now uses.
  if position('v_identity_id' in v_patched) > 0
     and position('v_identity_id uuid;' in v_patched) = 0 then
    v_patched := replace(
      v_patched,
      '  v_payment_status  booking_payment_status;',
      '  v_identity_id     uuid;' || chr(10) || '  v_payment_status  booking_payment_status;'
    );
  end if;

  -- Integrity shield: a booking must never be written with no money and no
  -- schedule. This assertion is what turns a future silent degradation into a
  -- loud failure instead of an empty row the customer is still charged for.
  if position('APEX_PAYLOAD_INTEGRITY' in v_patched) = 0 then
    v_patched := replace(
      v_patched,
      '  -- 1. Master booking row ----------------------------------------------------',
      '  -- APEX_PAYLOAD_INTEGRITY: refuse to persist a degraded payload.' || chr(10) ||
      '  if (v_booking ->> ' || quote_literal('total_amount') || ') is null' || chr(10) ||
      '     or (v_booking ->> ' || quote_literal('start_datetime') || ') is null then' || chr(10) ||
      '    raise exception ' || quote_literal('Booking payload is missing its total or schedule (total_amount=%, start_datetime=%). Aborting rather than saving an unusable booking.') ||
      ', v_booking ->> ' || quote_literal('total_amount') || ', v_booking ->> ' || quote_literal('start_datetime') || chr(10) ||
      '      using errcode = ' || quote_literal('check_violation') || ';' || chr(10) ||
      '  end if;' || chr(10) || chr(10) ||
      '  -- 1. Master booking row ----------------------------------------------------'
    );
  end if;

  execute v_patched;

  -- Verify the payload can no longer be erased.
  select pg_get_functiondef(p.oid)
    into v_patched
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'create_booking_atomic'
   limit 1;

  if position('to_jsonb(public.resolve_customer_by_email' in v_patched) > 0 then
    raise exception 'SC-1 payload repair: null-wiping jsonb_set is STILL present after the patch.';
  end if;

  if position('v_identity_id' in v_patched) = 0 then
    raise exception 'SC-1 payload repair: guarded identity assignment did not land.';
  end if;

  if position('APEX_PAYLOAD_INTEGRITY' in v_patched) = 0 then
    raise exception 'SC-1 payload repair: payload integrity assertion did not land.';
  end if;

  raise notice 'SC-1 payload repair applied: identity resolution can no longer erase the booking payload.';
end $repair_payload$;